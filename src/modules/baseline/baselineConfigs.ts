/**
 * Linux 基线配置快速编辑 — 配置项定义
 * 8 大分类，约 60+ 可编辑项
 */

// ─── 类型定义 ───

export type RiskLevel = 'critical' | 'high' | 'medium' | 'low';

export type ConfigItemType = 'boolean' | 'number' | 'string' | 'enum';

/** 发行版族群 — 同族命令/路径可互相回退 */
export type DistroFamily = 'debian' | 'redhat' | 'arch' | 'suse' | 'alpine' | 'generic';

/** 按发行版重写的字段集合，键为具体发行版 ID 或族群名 */
export interface DistroOverrides {
  /** 文件路径覆盖 (如 PAM 路径 Debian vs RHEL) */
  filePath?: string;
  /** 读取命令覆盖 */
  readCommand?: string;
  /** 写入命令覆盖 */
  writeCommand?: (value: string) => string;
  /** 备份命令覆盖 */
  backupCommand?: string;
  /** 重启命令覆盖 */
  restartCommand?: string;
}

export interface BaselineConfigItem {
  id: string;
  name: string;
  description: string;
  filePath: string;
  type: ConfigItemType;
  enumValues?: string[];
  defaultValue: string;
  recommendedValue: string;
  riskLevel: RiskLevel;
  readCommand: string;
  parseRegex: string;
  writeCommand: (value: string) => string;
  backupCommand: string;
  restartCommand?: string;
  restartService?: string;
  complianceRef?: string;
  validation?: { min?: number; max?: number; pattern?: string };
  /**
   * 按发行版/族群覆盖。键可以是：
   * - 具体发行版: 'ubuntu','centos','kylin','uos','deepin','openeuler','anolis','alpine'...
   * - 族群名: 'debian','redhat','arch','suse','alpine'
   * 解析优先级: 具体发行版 > 族群 > 默认字段
   */
  distroOverrides?: Record<string, DistroOverrides>;
}

export interface BaselineCategory {
  id: string;
  title: string;
  icon: string;       // icon-park 图标名
  hint?: string;
  items: BaselineConfigItem[];
}

// ─── 发行版族群映射 ───

export const distroFamilyMap: Record<string, DistroFamily> = {
  ubuntu: 'debian', debian: 'debian', kylin: 'debian', uos: 'debian', deepin: 'debian',
  centos: 'redhat', rhel: 'redhat', fedora: 'redhat', openeuler: 'redhat', anolis: 'redhat',
  arch: 'arch', opensuse: 'suse', alpine: 'alpine',
  generic: 'generic',
};

/**
 * 根据发行版 ID 解析配置项的实际值（filePath / readCommand / writeCommand 等）
 * 优先级：具体发行版 > 族群 > 默认
 */
export function resolveForDistro(
  item: BaselineConfigItem,
  distroId: string,
): { filePath: string; readCommand: string; writeCommand: (v: string) => string; backupCommand: string; restartCommand?: string } {
  const overrides = item.distroOverrides;
  const family = distroFamilyMap[distroId] || 'generic';

  // 查找优先级：具体发行版 → 族群 → 默认
  const match = overrides?.[distroId] || overrides?.[family];

  return {
    filePath: match?.filePath ?? item.filePath,
    readCommand: match?.readCommand ?? item.readCommand,
    writeCommand: match?.writeCommand ?? item.writeCommand,
    backupCommand: match?.backupCommand ?? item.backupCommand,
    restartCommand: match?.restartCommand ?? item.restartCommand,
  };
}

