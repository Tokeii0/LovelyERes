/** Alpine SSH 重启 (OpenRC) */
const alpineSshdRestart: DistroOverrides = {
  restartCommand: 'rc-service sshd restart 2>/dev/null || /etc/init.d/sshd restart 2>/dev/null',
};

/** Alpine 通用 service 启停 */
function alpineServiceOverride(svc: string): DistroOverrides {
  return {
    readCommand: `rc-status -a 2>/dev/null | grep -q '${svc}' && echo 'enabled' || echo 'not-found'`,
    writeCommand: (v: string) => v === 'enabled'
      ? `rc-update add ${svc} default 2>/dev/null; rc-service ${svc} start 2>/dev/null; true`
      : `rc-service ${svc} stop 2>/dev/null; rc-update del ${svc} 2>/dev/null; true`,
  };
}

